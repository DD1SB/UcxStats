#!/usr/bin/env bash
set -euo pipefail

if [[ $# -lt 1 || $# -gt 2 ]]; then
    echo "Usage: $0 <enumerations_dxcc_entity_code.tsv> [output.cs]" >&2
    exit 2
fi

input=$1
script_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
repo_root=$(CDPATH= cd -- "$script_dir/.." && pwd)
output=${2:-"$repo_root/src/UcxStats.Data/Dxcc/Adif317DxccCatalog.Generated.cs"}
expected_sha256=569e88410f5c69291e74a6b5f0d420647d4d109446c1596b4e3a38b73979dc15

if [[ ! -f "$input" ]]; then
    echo "Input file not found: $input" >&2
    exit 2
fi

actual_sha256=$(sha256sum "$input" | awk '{print $1}')
if [[ "$actual_sha256" != "$expected_sha256" ]]; then
    echo "Unexpected ADIF resource SHA-256: $actual_sha256" >&2
    echo "Expected: $expected_sha256" >&2
    exit 1
fi

temporary=$(mktemp)
trap 'rm -f "$temporary"' EXIT

awk -F '\t' '
BEGIN {
    print "// <auto-generated />"
    print "// Source: ADIF_317_resources_2026_03_22.zip"
    print "// File: 317/exports/tsv/enumerations_dxcc_entity_code.tsv"
    print "// SHA-256: 569e88410f5c69291e74a6b5f0d420647d4d109446c1596b4e3a38b73979dc15"
    print "namespace UcxStats.Data.Dxcc;"
    print ""
    print "internal static class Adif317DxccCatalogData"
    print "{"
    print "    internal static readonly DxccCatalogEntry[] Entries ="
    print "    ["
}
NR > 1 {
    sub(/\r$/, "", $8)
    if ($1 != "DXCC_Entity_Code" || $2 !~ /^[0-9]+$/ ||
        ($4 != "" && $4 != "Deleted") || $7 != "3.1.7" || $8 != "Released") {
        printf "Invalid or non-Released ADIF row at line %d\n", NR > "/dev/stderr"
        invalid = 1
        next
    }

    id = $2 + 0
    name = $3
    gsub(/\\/, "\\\\", name)
    gsub(/\"/, "\\\"", name)
    status = id == 0 ? "Unknown" : ($4 == "Deleted" ? "Deleted" : "Current")
    sentinel = id == 0 ? ", IsExplicitNonDxcc: true" : ""
    printf "        new(%d, DxccCatalogEntityStatus.%s, \"%s\"%s),\n", id, status, name, sentinel

    count++
    if (id == 0) sentinel_count++
    else if ($4 == "Deleted") deleted++
    else current++
}
END {
    print "    ];"
    print "}"
    if (invalid || count != 403 || current != 340 || deleted != 62 || sentinel_count != 1) {
        printf "Unexpected catalog totals: entries=%d current=%d deleted=%d sentinel=%d\n", \
            count, current, deleted, sentinel_count > "/dev/stderr"
        exit 1
    }
}
' "$input" > "$temporary"

mv "$temporary" "$output"
trap - EXIT
echo "Generated $output"
