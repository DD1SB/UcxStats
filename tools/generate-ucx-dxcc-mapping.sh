#!/usr/bin/env bash
set -euo pipefail

if [[ $# -lt 1 || $# -gt 2 ]]; then
    echo "Usage: $0 <UcxLog-8.50-Country0.txt> [output.cs]" >&2
    exit 2
fi

input=$1
script_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
repo_root=$(CDPATH= cd -- "$script_dir/.." && pwd)
output=${2:-"$repo_root/src/UcxStats.Data/Dxcc/UcxLog850CountryDxccMappings.Generated.cs"}
expected_sha256=05685def3be5880e8e09ace9fc87257f78ec27710d6cc3d73e0f414f80abce3f

if [[ ! -f "$input" ]]; then
    echo "Input file not found: $input" >&2
    exit 2
fi

actual_sha256=$(sha256sum "$input" | awk '{print $1}')
if [[ "$actual_sha256" != "$expected_sha256" ]]; then
    echo "Unexpected UcxLog country resource SHA-256: $actual_sha256" >&2
    echo "Expected UcxLog 8.50 Country0.txt: $expected_sha256" >&2
    exit 1
fi

temporary=$(mktemp)
trap 'rm -f "$temporary"' EXIT

awk '
function mapping_kind(code, entity_id) {
    if (substr(code, 1, 1) == "#") return "Historical"
    if (code == "4U_IT" || code == "PJ5/6" || code == "UA3" || code == "UA9" ||
        code == "VP8/F" || code == "VP8/H") return "Alias"
    return "Direct"
}
function rationale(code, entity_id) {
    if (code == "4U_IT") return "UcxLog label for ITU HQ (4U1ITU); distinct from WAE-only 4U_V."
    if (code == "PJ5/6") return "UcxLog combined label for the single Saba & St. Eustatius DXCC entity."
    if (code == "UA3") return "UcxLog regional label for European Russia."
    if (code == "UA9") return "UcxLog regional label for Asiatic Russia."
    if (code == "VP8/F") return "UcxLog qualified label for the Falkland Islands DXCC entity."
    if (code == "VP8/H") return "UcxLog qualified label for the South Shetland Islands DXCC entity."
    if (entity_id != "") return ""
    if (code == "4U_V" || code == "GM/S" || code == "IT" || code == "JW/B" || code == "TA1")
        return "UcxLog defines this as a WAE-only subdivision and supplies no numeric DXCC entity."
    return "UcxLog defines this as an R150S subdivision and supplies no numeric DXCC entity."
}
function escape(value) {
    gsub(/\\/, "\\\\", value)
    gsub(/\"/, "\\\"", value)
    return value
}
BEGIN {
    print "// <auto-generated />"
    print "// Source: official UcxLog 8.50 UcxLog.zip / COUNTRY.DAT / Country0.txt"
    print "// UcxLog.zip SHA-256: 6c972c70cf6284f784610394de2afe31039f51608d21f530a4e6c05015d1461f"
    print "// COUNTRY.DAT SHA-256: 4564deb87791947228984bc92d1181ab8574d517e1e9e038ecf91145effc2186"
    print "// Country0.txt SHA-256: 05685def3be5880e8e09ace9fc87257f78ec27710d6cc3d73e0f414f80abce3f"
    print "namespace UcxStats.Data.Dxcc;"
    print ""
    print "internal static class UcxLog850CountryDxccMappingData"
    print "{"
    print "    internal const int SourceEntityRowCount = 455;"
    print "    internal const int SourceDistinctCountryCodeCount = 452;"
    print "    internal const int SourceExplicitNonDxccCount = 0;"
    print ""
    print "    internal static readonly string[] DuplicateSourceCountryCodes = [\"I\", \"TA\", \"Z6\"];"
    print ""
    print "    internal static readonly UcxCountryDxccMapping[] Entries ="
    print "    ["
}
{
    sub(/\r$/, "")
    if ($0 ~ /^=T=/) stopped = 1
    if (stopped || index($0, ":") == 0) next

    right = substr($0, index($0, ":") + 1)
    gsub(/^[[:space:]]+|[[:space:]]+$/, "", right)
    field_count = split(right, fields, /[[:space:]]+/)
    if (field_count < 2 || fields[2] !~ /^(AF|AN|AS|EU|NA|OC|SA)$/) next

    source_rows++
    code = toupper(fields[1])
    entity_id = ""
    if (field_count >= 7 && fields[7] ~ /^[0-9][0-9]?[0-9]?$/) entity_id = fields[7] + 0

    if (!(code in first_index)) {
        order[++distinct] = code
        first_index[code] = distinct
        ids[code] = entity_id
    } else {
        duplicates[code]++
        if (ids[code] != "" && entity_id != "" && ids[code] != entity_id) {
            printf "Conflicting numeric identities for duplicate UCX code %s\n", code > "/dev/stderr"
            invalid = 1
        }
        if (ids[code] == "" && entity_id != "") ids[code] = entity_id
    }
}
END {
    for (i = 1; i <= distinct; i++) {
        code = order[i]
        entity_id = ids[code]
        if (entity_id == "") {
            unresolved++
            printf "        new(\"%s\", null, UcxDxccMappingKind.Unknown, \"%s\"),\n", \
                escape(code), escape(rationale(code, entity_id))
            continue
        }

        if (entity_id in target_seen) duplicate_targets++
        target_seen[entity_id]++
        kind = mapping_kind(code, entity_id)
        if (kind == "Historical") deleted++
        else current++
        text = rationale(code, entity_id)
        if (text == "")
            printf "        new(\"%s\", %d, UcxDxccMappingKind.%s),\n", escape(code), entity_id, kind
        else
            printf "        new(\"%s\", %d, UcxDxccMappingKind.%s, \"%s\"),\n", \
                escape(code), entity_id, kind, escape(text)
    }

    print "    ];"
    print "}"

    duplicate_code_count = 0
    for (code in duplicates) duplicate_code_count++
    if (invalid || source_rows != 455 || distinct != 452 || current != 340 || deleted != 62 ||
        unresolved != 50 || duplicate_code_count != 3 || duplicates["I"] != 1 ||
        duplicates["TA"] != 1 || duplicates["Z6"] != 1 || duplicate_targets != 0) {
        printf "Unexpected mapping totals: rows=%d distinct=%d current=%d deleted=%d unresolved=%d duplicate-codes=%d duplicate-targets=%d\n", \
            source_rows, distinct, current, deleted, unresolved, duplicate_code_count, duplicate_targets > "/dev/stderr"
        exit 1
    }
}
' "$input" > "$temporary"

mv "$temporary" "$output"
trap - EXIT
echo "Generated $output"
